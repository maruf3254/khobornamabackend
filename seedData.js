    let admin = await User.findOne({ email: 'admin@news.com' });

    if (!admin) {
      admin = await User.create({
        name: 'প্রশাসক',
        email: 'admin@news.com',
        password: 'admin123',
        role: 'admin'
      });

      console.log('✅ অ্যাডমিন অ্যাকাউন্ট তৈরি হয়েছে');
    }

    // সাধারণ পরীক্ষামূলক ব্যবহারকারী
