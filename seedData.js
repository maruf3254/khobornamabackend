    const publishedCount = createdNews.filter(
      news => news.status === 'published'
    ).length;

    const draftCount = createdNews.filter(
      news => news.status === 'draft'
    ).length;

    console.log('\n========================================');
    console.log('🎉 ডেটাবেজ সফলভাবে তৈরি হয়েছে!');
    console.log('========================================\n');

