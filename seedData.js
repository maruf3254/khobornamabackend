    if (!testUser) {
      testUser = await User.create({
        name: 'রহিম আহমেদ',
        email: 'user@news.com',
        password: 'user123',
        role: 'user'
      });

      console.log('✅ সাধারণ ব্যবহারকারী তৈরি হয়েছে');
    }

    // সংবাদ তৈরি
    console.log('সংবাদ তৈরি করা হচ্ছে...');

    const createdNews = [];

    for (const newsItem of sampleNews) {
      const news = await News.create({
        ...newsItem,
        author: admin._id,
        publishedAt:
          newsItem.status === 'published'
            ? new Date(Date.now() - Math.random() * 7 * 24 * 60 * 60 * 1000)
            : null,
        likes:
          newsItem.status === 'published'
            ? [testUser._id]
            : [],
        likesCount:
          newsItem.status === 'published'
            ? 1
            : 0
      });

      createdNews.push(news);
    }

    console.log(`✅ মোট ${createdNews.length}টি সংবাদ তৈরি হয়েছে`);

    // মন্তব্য তৈরি
    console.log('মন্তব্য তৈরি করা হচ্ছে...');

    for (const commentData of sampleComments) {
      await Comment.create({
        content: commentData.content,
        news: createdNews[commentData.newsIndex]._id,
        user: testUser._id
      });
    }

    console.log(`✅ মোট ${sampleComments.length}টি মন্তব্য তৈরি হয়েছে`);

